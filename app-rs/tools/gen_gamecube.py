#!/usr/bin/env python3
"""Turn the Python app's GameCube artwork (`app/gamecube_textures.py`) into Rust data.

The Python module keeps each replacement region as base85(zlib(bytes)); this decodes them once, so the Rust build
does not need base85 or zlib at all: `crates/shb-core/src/gamecube_textures.rs` holds the table and
`gamecube_textures.bin` the bytes, embedded with `include_bytes!`.

    python tools/gen_gamecube.py --app F:/project/super-hero-boost/app --out crates/shb-core/src
    python tools/gen_gamecube.py --app ... --out ... --check     # fails when the files are stale
"""

import argparse
import base64
import hashlib
import sys
import zlib
from pathlib import Path


def build(app: Path):
    sys.path.insert(0, str(app))
    from gamecube_textures import ATLAS_SIZE, LEGACY_ATLAS_HASHES, TEXTURES  # noqa: E402

    blob = bytearray()
    rows = []
    for offset, size, digest, encoded in TEXTURES:
        raw = zlib.decompress(base64.b85decode(encoded))
        if len(raw) != size:
            raise SystemExit(f"region {offset}: {len(raw)} bytes, the table says {size}")
        # `digest` is the SHA-256 of the *original* region in the game's atlas (the check that this is the archive
        # we know), not of the replacement.
        rows.append((offset, size, digest, len(blob)))
        blob += raw

    lines = [
        "// Generated by tools/gen_gamecube.py from the Python app's `gamecube_textures.py`. Do not edit.",
        "//",
        "// Each row is (offset in the game's UI atlas, size, SHA-256 of the original bytes there, start in",
        "// REPLACEMENTS). The digest is what proves the archive is the one this artwork was cut for.",
        "",
        f"pub const ATLAS_SIZE: usize = {ATLAS_SIZE};",
        "",
        "/// The hashes of the standalone `GameCube-System-Controller` atlases this app made before.",
        "pub static LEGACY_ATLAS_HASHES: &[&str] = &[",
    ]
    for digest in sorted(LEGACY_ATLAS_HASHES):
        lines.append(f'    "{digest}",')
    lines += [
        "];",
        "",
        "/// The bytes of every replacement, back to back.",
        'pub static REPLACEMENTS: &[u8] = include_bytes!("gamecube_textures.bin");',
        "",
        "pub static TEXTURES: &[(usize, usize, &str, usize)] = &[",
    ]
    for offset, size, digest, start in rows:
        lines.append(f'    ({offset}, {size}, "{digest}", {start}),')
    lines += ["];", ""]
    return "\n".join(lines), bytes(blob)


def main() -> int:
    ap = argparse.ArgumentParser()
    here = Path(__file__).resolve().parents[1]
    ap.add_argument("--app", type=Path, default=here.parent / "app")
    ap.add_argument("--out", type=Path, default=here / "crates" / "shb-core" / "src")
    ap.add_argument("--check", action="store_true", help="only verify the generated files are current")
    args = ap.parse_args()

    source, blob = build(args.app)
    rs = args.out / "gamecube_textures.rs"
    bin_path = args.out / "gamecube_textures.bin"
    if args.check:
        stale = []
        if not rs.is_file() or rs.read_text(encoding="utf-8") != source:
            stale.append(str(rs))
        if not bin_path.is_file() or bin_path.read_bytes() != blob:
            stale.append(str(bin_path))
        if stale:
            print("stale:", ", ".join(stale))
            return 1
        print(f"gamecube_textures: {len(blob)} bytes, up to date")
        return 0
    rs.parent.mkdir(parents=True, exist_ok=True)
    rs.write_text(source, encoding="utf-8")
    bin_path.write_bytes(blob)
    print(f"gamecube_textures.rs ({len(source)} bytes) and .bin ({len(blob)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
