def tr(lang: str, key: str, **kw) -> str:
    s = T.get(lang, T["en"]).get(key) or T["en"].get(key, key)
    try:
        return s.format(**kw)
    except Exception:
        return s


def system_lang() -> str:
    """Best-effort UI language on Windows, macOS and Linux."""
    loc = (os.environ.get("LC_ALL") or os.environ.get("LC_MESSAGES") or os.environ.get("LANG") or "")
    if not loc and os.name == "nt":
        try:
            import ctypes
            lid = ctypes.windll.kernel32.GetUserDefaultUILanguage() & 0x3FF
            win = {0x09: "en", 0x0A: "es", 0x16: "pt", 0x0C: "fr", 0x07: "de", 0x10: "it"}
            if lid in win:
                return win[lid]
        except Exception:
            pass
    if not loc:
        try:
            import locale
            loc = locale.getdefaultlocale()[0] or ""
        except Exception:
            loc = ""
    code = loc.replace("-", "_").split(".")[0].split("_")[0].lower()
    return code if code in LANGS else "en"
